-- Bundles src/ modules into the single plugin entry file plugin/main.lua.
-- Usage (from repo root): lua5.4 tools/bundle.lua [--check]
local HEADER = "-- Generated by tools/bundle.lua from src/. Do not edit.\n"
  .. "local uz = uz or fb  -- Uzume < 0.22 only has the old name fb\n"
local OUT = "plugin/main.lua"

local function read(path)
  local f = io.open(path, "rb")
  if not f then return nil end
  local s = f:read("a")
  f:close()
  return s
end

local names = {}
for line in (read("src/modules.txt") or error("src/modules.txt missing")):gmatch("[^\r\n]+") do
  line = line:match("^%s*(.-)%s*$")
  if line ~= "" and line:sub(1, 1) ~= "#" then names[#names + 1] = line end
end
table.sort(names)

local parts = {
  HEADER,
  "local __mod = {}\n",
  "local __loaded = {}\n",
  "local function require(name)\n",
  "  local m = __loaded[name]\n",
  "  if m ~= nil then\n",
  "    if m == __loaded then return nil end\n",
  "    return m\n",
  "  end\n",
  "  local f = __mod[name]\n",
  "  if not f then return nil end\n",
  "  __loaded[name] = __loaded -- cycle guard\n",
  "  local r = f(name)\n",
  "  if r == nil then r = true end\n",
  "  __loaded[name] = r\n",
  "  return r\n",
  "end\n",
}
-- A module whose file is absent is skipped (optional adapters); main must exist.
for _, name in ipairs(names) do
  local src = read("src/" .. name:gsub("%.", "/") .. ".lua")
  if src then
    parts[#parts + 1] = string.format("__mod[%q] = function(...)\n%s\nend\n", name, src)
  elseif name == "main" then
    error("src/main.lua missing")
  end
end
parts[#parts + 1] = 'require("main")\n'
local out = table.concat(parts)

if arg[1] == "--check" then
  if read(OUT) ~= out then
    io.stderr:write(OUT .. " is stale; run: lua5.4 tools/bundle.lua\n")
    os.exit(1)
  end
  print(OUT .. " is up to date")
else
  local f = assert(io.open(OUT, "wb"))
  f:write(out)
  f:close()
  print("wrote " .. OUT)
end
